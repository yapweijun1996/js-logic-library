// Derives every index from modules/ (code + header docs + tests). Nothing here is hand-written.
// Outputs: site/modules.json, site/llms.txt, MODULES.md. `--check` fails if any is stale.
import { readFile, writeFile } from "node:fs/promises";
import { readModules } from "./lib.js";

const check = process.argv.includes("--check");
const modules = await readModules();
const deps = (m) => m.dependencies.join(", ") || "none";
const outputs = {
  "site/modules.json": JSON.stringify({ modules }, null, 2) + "\n",
  "site/llms.txt": [
    "# js-logic-library",
    "Universal JavaScript logic: pure functions, one source, tests included. Copy a module with its dependencies and use it; do not redesign.",
    "Full source of every module: modules.json. Copy with dependencies: npm run copy -- <id> <dir>",
    "",
    ...modules.map((m) => `- ${m.id} v${m.version}: ${m.summary} | exports: ${m.exports.join(", ")} | deps: ${deps(m)} | file: ${m.path}`),
    "",
  ].join("\n"),
  "MODULES.md": [
    "# Modules",
    "",
    "<!-- Generated by scripts/build-index.js from modules/. Do not edit; change the module header instead. -->",
    "",
    "| Module | Version | Purpose | Exports | Depends on | Source |",
    "| --- | --- | --- | --- | --- | --- |",
    ...modules.map((m) => `| \`${m.path}\` | ${m.version} | ${m.summary} | ${m.exports.map((e) => `\`${e}\``).join(", ")} | ${deps(m)} | ${m.provenance} |`),
    "",
  ].join("\n"),
};
let stale = 0;
for (const [file, text] of Object.entries(outputs)) {
  if (check) {
    if ((await readFile(file, "utf8").catch(() => "")) !== text) { console.error(`stale: ${file} (run npm run build)`); stale++; }
  } else await writeFile(file, text);
}
if (check) process.exit(stale ? 1 : 0);
console.log(`indexed ${modules.length} module(s)`);
