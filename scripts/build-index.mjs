// Single source of truth: src/*.js (code + header docs) and tests/*.test.mjs.
// Everything else here is derived from them, for humans and agents alike:
// site/modules.json, site/llms.txt, docs/MODULES.md. `--check` fails if any is stale.
import { readdir, readFile, writeFile } from "node:fs/promises";

const check = process.argv.includes("--check");

const names = (await readdir("src")).filter((f) => f.endsWith(".js")).sort();
const modules = [];
for (const file of names) {
  const id = file.replace(/\.js$/, "");
  const source = await readFile(`src/${file}`, "utf8");
  const test = await readFile(`tests/${id}.test.mjs`, "utf8").catch(() => "");
  const header = [];
  for (const line of source.split("\n")) {
    if (!line.startsWith("//")) break;
    header.push(line.replace(/^\/\/ ?/, ""));
  }
  const exports = [...source.matchAll(/^export (?:const|function) (\w+)/gm)].map((m) => m[1]);
  const imports = [...source.matchAll(/^import .* from "(.+)"/gm)].map((m) => m[1]);
  modules.push({
    id, path: `src/${file}`, testPath: test ? `tests/${id}.test.mjs` : null,
    summary: header[0] ?? "", notes: header.slice(1).join("\n"), exports, dependencies: imports, source, test,
  });
}
const rows = modules.map((m) => `| \`${m.path}\` | ${m.summary} | ${m.exports.map((e) => `\`${e}\``).join(", ")} | ${m.dependencies.join(", ") || "none"} |`);
const outputs = {
  "site/modules.json": JSON.stringify({ modules }, null, 2) + "\n",
  "site/llms.txt": [
    "# js-logic-library",
    "Pure, dependency-free JS modules. Copy one file from src/ (plus its test) and use it; do not redesign.",
    "Machine-readable index with full source: modules.json",
    "",
    ...modules.map((m) => `- ${m.id}: ${m.summary} | exports: ${m.exports.join(", ")} | deps: ${m.dependencies.join(", ") || "none"} | file: ${m.path}`),
    "",
  ].join("\n"),
  "docs/MODULES.md": [
    "# Modules",
    "",
    "<!-- Generated by scripts/build-index.mjs from src/ and tests/. Do not edit; change the module header instead. -->",
    "",
    "| File | Purpose | Exports | Depends on |",
    "| --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n"),
};
let stale = 0;
for (const [file, text] of Object.entries(outputs)) {
  if (check) {
    if ((await readFile(file, "utf8").catch(() => "")) !== text) { console.error(`stale: ${file} (run npm run build)`); stale++; }
  } else await writeFile(file, text);
}
if (check) process.exit(stale ? 1 : 0);
console.log(`indexed ${modules.length} module(s)`);
